require "bundler/setup"
require "fileutils"
require "tmpdir"
require "json"
require "digest"
require "brotli"
require_relative "../lib/wani/version"

def prune_browser_rouge(lib)
  lexers = %w[css diff html javascript json jsx markdown plain_text python ruby shell sql tsx typescript xml yaml]
  Dir.children(File.join(lib, "rouge/lexers")).each do |entry|
    # Keep auxiliary directories for the selected lexers, such as TypeScript.
    FileUtils.rm_r(File.join(lib, "rouge/lexers", entry)) unless lexers.include?(File.basename(entry, ".rb"))
  end
  FileUtils.rm_r(File.join(lib, "rouge/demos"))

  # Rouge 5.1.0 preloads Julia before discovering the installed lexers.
  entrypoint = File.join(lib, "rouge.rb")
  source = File.read(entrypoint)
  abort "Unexpected Rouge entrypoint; review the browser lexer list" unless source.sub!("  require_relative 'rouge/lexers/julia'\n", "")
  File.write(entrypoint, source)
end

def defer_kramdown_yaml(path)
  source = File.read(path)
  removed = source.sub!(/^require 'yaml'\n/, "")
  deferred = source.sub!("          val = YAML.safe_load(val)\n        rescue RuntimeError",
    "          require 'yaml'\n          val = YAML.safe_load(val)\n        rescue LoadError, RuntimeError")
  abort "Unexpected Kramdown YAML loading code" unless removed && deferred
  File.write(path, source)
end

minimal = ARGV == ["--minimal"]
abort "Usage: bundle exec ruby scripts/build_wasm.rb [--minimal]" unless ARGV.empty? || minimal
require_relative "build_wasm_runtime"

root = File.expand_path("..", __dir__)
Dir.chdir(root) do
  abort "Run npm ci before building the minimal WASM" if minimal && !File.file?("node_modules/@ruby/wasm-wasi/package.json")
  loader_root = "third_party/ruby-wasm-loader"
  provenance = JSON.parse(File.read("#{loader_root}/provenance.json"))
  loader = "#{loader_root}/browser.script.iife.js"
  abort "PR loader checksum mismatch" unless Digest::SHA256.file(loader).hexdigest == provenance.fetch("loader_sha256")
  source_digest = Digest::SHA256.new
  build_sources = %w[Gemfile.lock scripts/build_wasm.rb scripts/build_wasm_runtime.rb
    scripts/detect_wasm_extensions.mjs assets/bootstrap.rb templates/slides.md]
  build_sources << "scripts/patches/#{File.basename(WANI_WASM_PRISM_ONLY_PATCH)}"
  (Dir["lib/wani/{core,browser}/**/*.rb"] + build_sources).sort.each { |file| source_digest << file << File.binread(file) }
  Dir.mktmpdir("wani-pack-") do |stage|
    app = File.join(stage, "app")
    FileUtils.mkdir_p("#{app}/lib/wani")
    %w[core browser].each { |name| FileUtils.cp_r("lib/wani/#{name}", "#{app}/lib/wani/") }
    %w[kramdown rexml kramdown-parser-gfm rouge].each do |name|
      spec = Gem::Specification.find_by_name(name)
      destination = File.join(app, "bundle", name)
      FileUtils.mkdir_p(destination)
      FileUtils.cp_r(File.join(spec.full_gem_path, "lib"), destination)
    end
    defer_kramdown_yaml(File.join(app, "bundle/kramdown/lib/kramdown/options.rb")) if minimal
    prune_browser_rouge(File.join(app, "bundle", "rouge", "lib"))
    base = build_wasm_runtime(stage, omit_yaml: minimal)
    runtime = File.join(stage, "runtime")
    mappings = [
      "--dir", "#{runtime}/usr::/usr", "--dir", "#{runtime}/bundle::/bundle",
      "--dir", "#{app}::/wani"]
    pack = ->(base, output) do
      abort "Packaging failed" unless system("bundle", "exec", "rbwasm", "pack", base, *mappings, "--output", output)
    end
    if minimal
      probe = File.join(stage, "probe.wasm")
      pack.call(base, probe)
      base = build_wasm_runtime(stage, extensions: detect_wasm_extensions(probe))
    end
    pack.call(base, "assets/wani.wasm")
    File.binwrite(File.join(stage, "wani.wasm.br"), Brotli.deflate(File.binread("assets/wani.wasm"), quality: 11))
    FileUtils.mv(File.join(stage, "wani.wasm.br"), "assets/wani.wasm.br")
  end
  require "rouge"
  File.write("assets/highlight.css", "/* Generated by scripts/build_wasm.rb with Rouge #{Rouge.version}. */\n" + Rouge::Themes::Github.render(scope: ".highlight") + "\n")
  FileUtils.cp(File.join(Gem::Specification.find_by_name("rouge").full_gem_path, "LICENSE"), "assets/rouge.LICENSE")
  FileUtils.cp(loader, "assets/runtime.pr672.js")
  %w[LICENSE NOTICE].each { |name| FileUtils.cp("#{loader_root}/#{name}", "assets/runtime.#{name}") }
  File.write("assets/build.json", JSON.pretty_generate({ version: Wani::VERSION, source_sha256: source_digest.hexdigest, loader_commit: provenance.fetch("commit"), wasm_profile: minimal ? "minimal" : "full", wasm_sha256: Digest::SHA256.file("assets/wani.wasm").hexdigest }))
  puts "Built assets/wani.wasm (#{File.size('assets/wani.wasm')} bytes)"
end
